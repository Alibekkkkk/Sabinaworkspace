// Computes WCAG contrast for every text/background token pair in both themes and writes
// docs/DESIGN_TOKENS.md.  `npm run tokens:contrast`  (exits 1 if a pair is below its threshold).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const cssPath = new URL("../css/design-system.css", import.meta.url);

// [foreground token, background token, minimum ratio, what it is used for]
export const PAIRS = [
  ["text", "background", 4.5, "Body text on the page"],
  ["text", "surface", 4.5, "Body text on cards"],
  ["muted", "background", 4.5, "Secondary text on the page"],
  ["muted", "surface", 4.5, "Secondary text on cards"],
  ["muted", "surface-raised", 4.5, "Secondary text on raised panels"],
  ["primary", "surface", 4.5, "Links and primary text on cards"],
  ["primary", "background", 4.5, "Links on the page"],
  ["on-primary", "primary", 4.5, "Text on primary buttons"],
  ["text", "primary-soft", 4.5, "Text on selected / soft brand chips"],
  ["primary-strong", "primary-soft", 4.5, "Brand text on soft brand chips"],
  ["accent", "surface", 4.5, "Accent text on cards"],
  ["text", "accent-soft", 4.5, "Text on accent chips"],
  ["success", "surface", 4.5, "Success text on cards"],
  ["success", "success-soft", 4.5, "Success feedback sheet"],
  ["warning", "warning-soft", 4.5, "Warning banner"],
  ["danger", "surface", 4.5, "Error text on cards"],
  ["danger", "danger-soft", 4.5, "Error feedback sheet"],
  ["text", "info-soft", 4.5, "Information banner"],
  ["mark-ink", "mark-yellow", 4.5, "Yellow highlighter"],
  ["mark-ink", "mark-green", 4.5, "Green highlighter"],
  ["mark-ink", "mark-blue", 4.5, "Blue highlighter"],
  ["mark-ink", "mark-pink", 4.5, "Pink highlighter"],
  ["focus", "surface", 3, "Focus ring against cards (non-text, 3:1)"],
  ["focus", "background", 3, "Focus ring against the page (non-text, 3:1)"],
  ["border-strong", "surface", 3, "Input borders (non-text, 3:1)"]
];

export function readThemes(css = readFileSync(cssPath, "utf8")) {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const blocks = [...withoutComments.matchAll(/([^{}]+)\{([^{}]*)\}/g)];
  const read = predicate => Object.fromEntries(
    blocks.filter(block => predicate(block[1].trim()))
      .flatMap(block => [...block[2].matchAll(/--ds-(?:color|mark)-([a-z-]+):\s*(#[0-9a-fA-F]{6})/g)].map(match => [match[0].includes("--ds-mark") ? `mark-${match[1]}` : match[1], match[2]]))
  );
  const light = read(selector => selector.startsWith(":root"));
  const dark = { ...light, ...read(selector => selector.includes('html[data-theme="dark"]')) };
  return { light, dark };
}

function channel(value) {
  const normalised = value / 255;
  return normalised <= 0.03928 ? normalised / 12.92 : ((normalised + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map(index => channel(parseInt(hex.slice(index, index + 2), 16)));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(foreground, background) {
  const [high, low] = [luminance(foreground), luminance(background)].sort((a, b) => b - a);
  return (high + 0.05) / (low + 0.05);
}

export function evaluate(themes = readThemes()) {
  return Object.entries(themes).flatMap(([theme, tokens]) => PAIRS.map(([foreground, background, minimum, use]) => {
    const fg = tokens[foreground];
    const bg = tokens[background];
    const ratio = fg && bg ? contrast(fg, bg) : 0;
    return { theme, foreground, background, minimum, use, fg, bg, ratio, pass: ratio >= minimum };
  }));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const rows = evaluate();
  const lines = [
    "# Design tokens: contrast table", "",
    "Generated by `npm run tokens:contrast` from `css/design-system.css`. Do not edit by hand. Text needs 4.5:1; focus rings and input borders need 3:1 (WCAG 2.2 AA).", "",
    "| Theme | Foreground | Background | Ratio | Needs | Result | Used for |", "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows.map(row => `| ${row.theme} | \`${row.foreground}\` ${row.fg || "?"} | \`${row.background}\` ${row.bg || "?"} | ${row.ratio.toFixed(2)} | ${row.minimum} | ${row.pass ? "pass" : "**FAIL**"} | ${row.use} |`),
    "",
    "## Scales", "",
    "- **Neutral:** `background` < `surface` < `surface-raised`, with `border` and `border-strong`; `text` and `muted` for copy.",
    "- **Brand:** `primary`, `primary-strong`, `primary-soft`, `on-primary`, plus `accent` / `accent-soft`.",
    "- **Status:** `success`, `warning`, `danger` each with a `-soft` background; `info-soft`.",
    "- **Highlighters:** `mark-yellow|green|blue|pink` always carry `mark-ink` text.",
    "- **Type:** fluid `--ds-text-xs` to `--ds-text-3xl` (clamp), reading size and measure tokens. **Space:** 4-point grid `--ds-space-1..8`. **Radius:** xs to pill. **Elevation:** sm/md/lg. **Motion:** fast/base/slow + `ease-out`/`ease-spring`. **Layers:** base, sticky, nav, drawer, modal, toast.", ""
  ];
  writeFileSync(fileURLToPath(new URL("../docs/DESIGN_TOKENS.md", import.meta.url)), lines.join("\n"));
  const failures = rows.filter(row => !row.pass);
  console.log(`${rows.length - failures.length}/${rows.length} pairs pass.`);
  for (const row of failures) console.log(`FAIL ${row.theme}: ${row.foreground} on ${row.background} = ${row.ratio.toFixed(2)} (needs ${row.minimum})`);
  process.exit(failures.length ? 1 : 0);
}
