// Adds <link rel="modulepreload"> hints for each page's own module graph, so the browser fetches all of a page's modules in
// parallel instead of discovering them one import at a time.
//   node scripts/build-preload.mjs           rewrites the generated block in each page's <head>
//   node scripts/build-preload.mjs --check   exits 1 if a page is out of date (the unit tests run this too)
import { readFileSync, writeFileSync } from "node:fs";
import { posix } from "node:path";
import { fileURLToPath } from "node:url";
import { graph, pages } from "./check-budgets.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const BEGIN = "<!-- modulepreload (generated by scripts/build-preload.mjs) -->"; const END = "<!-- /modulepreload -->";

export function hintsFor(html) {
  const entries = [...html.matchAll(/<script type="module" src="([^"]+)"/g)].map(match => posix.normalize(match[1]));
  const files = new Set();
  for (const entry of entries) graph(entry).eager.forEach(path => { if (path.endsWith(".js")) files.add(path); });
  for (const entry of entries) files.delete(entry); // the page already requests its own entry script
  return [...files].sort().map(path => `  <link rel="modulepreload" href="${path}">`).join("\n");
}

export function apply(html) {
  const hints = hintsFor(html);
  const block = hints ? `${BEGIN}\n${hints}\n  ${END}` : "";
  const from = html.indexOf(BEGIN);
  if (from >= 0) { const to = html.indexOf(END, from) + END.length; return `${html.slice(0, from)}${block}${html.slice(to)}`; }
  if (!block) return html;
  const anchor = html.search(/<script\b/); // before the first script in <head>
  return `${html.slice(0, anchor)}${block}\n  ${html.slice(anchor)}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check"); let stale = 0;
  for (const page of pages()) {
    const raw = readFileSync(root + page, "utf8"); const crlf = raw.includes("\r\n"); const html = raw.replace(/\r\n/g, "\n");
    const next = apply(html);
    if (next !== html) { stale += 1; if (!check) writeFileSync(root + page, crlf ? next.replace(/\n/g, "\r\n") : next); console.log(`${check ? "out of date" : "updated"}: ${page}`); }
  }
  if (check && stale) { console.error("Run: node scripts/build-preload.mjs"); process.exit(1); }
  console.log(check ? "modulepreload hints are up to date." : "done.");
}
